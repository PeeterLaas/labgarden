# Real shinymcp + R -> Node -> shared change service integration (no model/API key).
if (dir.exists(".r-library")) .libPaths(c(normalizePath(".r-library"), .libPaths()))
source("R/workspace.R")
source("R/mcp-tools.R")
workspace <- tempfile("paivik-r-", fileext = ".json")
Sys.setenv(PAIVIK_WORKSPACE = workspace)
app <- shinymcp::mcp_app(shiny::fluidPage(shiny::verbatimTextOutput("proposal")), tools = paivik_tools(), name = "paivik-test")
definitions <- app$tool_definitions()
names <- vapply(definitions, function(x) x$name, "")
stopifnot(length(names) == 6L, !any(grepl("approve|commit|discard", names)))
status <- app$call_tool("workspace_status", list())
stopifnot(!isTRUE(status$isError))
draft <- app$call_tool("draft_observation", list(project_id = "p-local", text = "Water looked cloudy at station 8."))
stopifnot(!isTRUE(draft$isError))
pending <- paivik_request("list")
stopifnot(length(pending) == 1L, identical(paivik_request("status")$records, 0L))
p <- paivik_request("preview", id = pending[[1]]$id)
bad <- try(paivik_request("commit", id = p$id), silent = TRUE)
stopifnot(inherits(bad, "try-error"), identical(paivik_request("status")$records, 0L))
approval <- list(confirmed = TRUE, proposalId = p$id, revision = p$revision, hash = p$hash, actor = "local-user", method = "typed")
invisible(paivik_request("commit", id = p$id, confirmation = approval))
stopifnot(identical(paivik_request("status")$records, 1L))
found <- app$call_tool("search_records", list(query = "cloudy"))
stopifnot(!isTRUE(found$isError), grepl("cloudy", paivik_json(found)))
unknown <- try(app$call_tool("commit", list()), silent = TRUE)
stopifnot(inherits(unknown, "try-error") || isTRUE(unknown$isError))
# Commit clears drafts it made out of date; a person can discard one; neither touches records.
first <- paivik_request("draft_observation", project = "p-local", text = "First pending note.")
second <- paivik_request("draft_observation", project = "p-local", text = "Second pending note.")
third <- paivik_request("draft_observation", project = "p-local", text = "Third pending note.")
gone <- paivik_request("discard", id = third$id)
stopifnot(identical(gone$discarded, third$id), length(paivik_request("list")) == 2L, identical(paivik_request("status")$records, 1L))
approval <- list(confirmed = TRUE, proposalId = first$id, revision = first$revision, hash = first$hash, actor = "local-user", method = "typed")
committed <- paivik_request("commit", id = first$id, confirmation = approval)
stopifnot(length(committed$removedOutdated) == 1L, identical(committed$removedOutdated[[1]]$id, second$id), length(paivik_request("list")) == 0L)
unlink(workspace)
system2 <- function(...) structure(character(), status = 127L)
no_output <- try(paivik_request("status"), silent = TRUE)
stopifnot(inherits(no_output, "try-error"), grepl("returned no response", no_output))
system2 <- function(...) structure("not JSON", status = 1L)
bad_output <- try(paivik_request("status"), silent = TRUE)
stopifnot(inherits(bad_output, "try-error"), grepl("invalid response", bad_output))
rm(system2)
cat("R/shinymcp integration passed: draft-only model tools, explicit approval, durable commit and search.\n")
